namespace BuildingBlocks.Analyzers.Tests;

public sealed class SaveChangesInHandlerAnalyzerTests
{
    private const string Prelude = """
        using System;
        using System.Threading;
        using System.Threading.Tasks;
        using BuildingBlocks.Core.Handlers;
        using Microsoft.EntityFrameworkCore;
        using Wolverine;
        using Wolverine.Attributes;

        public sealed class ShopDb(DbContextOptions<ShopDb> options) : DbContext(options);

        public sealed record PlaceOrder;

        """;

    [Theory]
    [InlineData("""
        public sealed class PlaceOrderHandler(IRequestContext context, ShopDb db) : CommandHandler<ShopDb>(context, db)
        {
            public async Task Handle(PlaceOrder command, CancellationToken ct) => await Db.SaveChangesAsync(ct);
        }
        """)]
    [InlineData("""
        public static class OrderPlacedHandler
        {
            public static void Handle(PlaceOrder message, ShopDb db) => db.SaveChanges();
        }
        """)]
    [InlineData("""
        public static class OrderConsumer
        {
            public static Task Consume(PlaceOrder message, ShopDb db) => db.SaveChangesAsync();
        }
        """)]
    [InlineData("""
        [WolverineHandler]
        public static class Fulfilment
        {
            public static void Handles(PlaceOrder message, ShopDb db) => db.SaveChanges();
        }
        """)]
    [InlineData("""
        public sealed class Shipping : IWolverineHandler
        {
            public void Handle(PlaceOrder message, ShopDb db) => db.SaveChanges();
        }
        """)]
    [InlineData("""
        public static class LambdaHandler
        {
            public static void Handle(PlaceOrder message, ShopDb db)
            {
                Action save = () => db.SaveChanges();
                save();
            }
        }
        """)]
    [InlineData("""
        public static class LocalFunctionHandler
        {
            public static void Handle(PlaceOrder message, ShopDb db)
            {
                Save();
                void Save() => db.SaveChanges();
            }
        }
        """)]
    public async Task SavingInsideAHandlerIsAnError(string handler)
    {
        var findings = await AnalyzerHarness.RunAsync(new SaveChangesInHandlerAnalyzer(), Prelude + handler);

        var finding = Assert.Single(findings);
        Assert.Equal(DiagnosticIds.SaveChangesInHandler, finding.Id);
    }

    [Theory]
    [InlineData("""
        public sealed class Seeder(ShopDb db)
        {
            public Task SeedAsync() => db.SaveChangesAsync();
        }
        """)]
    [InlineData("""
        public static class PlaceOrderHandler
        {
            public static void Handle(PlaceOrder message) { }

            private static void Helper(ShopDb db) => db.SaveChanges();
        }
        """)]
    [InlineData("""
        public sealed class Outbox { public Task SaveChangesAsync() => Task.CompletedTask; }

        public static class PlaceOrderHandler
        {
            public static Task Handle(PlaceOrder message, Outbox outbox) => outbox.SaveChangesAsync();
        }
        """)]
    [InlineData("""
        public static class OrderValidator
        {
            public static void Handle(PlaceOrder message, ShopDb db) => db.SaveChanges();
        }
        """)]
    [InlineData("""
        public sealed class PlaceOrderHandler
        {
            public Task HandleAsync(PlaceOrder message, ShopDb db, CancellationToken ct) => db.SaveChangesAsync(ct);
        }
        """)]
    [InlineData("""
        // <auto-generated/>
        public static class GeneratedPlaceOrderHandler
        {
            public static void Handle(PlaceOrder message, ShopDb db) => db.SaveChanges();
        }
        """)]
    public async Task SavingOutsideHandlerScopeIsAllowed(string code)
    {
        const string header = "// <auto-generated/>";
        var source = code.StartsWith(header, StringComparison.Ordinal)
            ? header + "\n" + Prelude + code[header.Length..]
            : Prelude + code;

        Assert.Empty(await AnalyzerHarness.RunAsync(new SaveChangesInHandlerAnalyzer(), source));
    }
}
